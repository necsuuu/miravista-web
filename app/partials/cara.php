      <h2 id="cara-titulo">¿Qué armazón va con tu cara?</h2>
      <p>Elegí la forma que más se parece a la tuya y mirá cómo quedan los distintos armazones. Es una guía para arrancar: en la óptica te ayudamos a probártelos.</p>
    </div>
